"""Interfaces the core needs from the outside world (implemented in infrastructure)."""

from typing import Protocol

from stock.core.entities.customer_order import CustomerOrder
from stock.core.entities.notification import Notification
from stock.core.entities.product import Product
from stock.core.entities.purchase_request import PurchaseRequest
from stock.core.entities.supplier_order import SupplierOrder
from stock.core.roles import Role


class ProductRepository(Protocol):
    def get(self, product_id: int) -> Product | None: ...
    def get_by_sku(self, sku: str) -> Product | None: ...
    def list(self) -> list[Product]: ...
    def add(self, product: Product) -> Product: ...
    def save(self, product: Product) -> None: ...


class CustomerOrderRepository(Protocol):
    def get(self, order_id: int) -> CustomerOrder | None: ...
    def list(self) -> list[CustomerOrder]: ...
    def add(self, order: CustomerOrder) -> CustomerOrder: ...
    def save(self, order: CustomerOrder) -> None: ...


class PurchaseRequestRepository(Protocol):
    def get(self, request_id: int) -> PurchaseRequest | None: ...
    def list(self) -> list[PurchaseRequest]: ...
    def add(self, request: PurchaseRequest) -> PurchaseRequest: ...
    def save(self, request: PurchaseRequest) -> None: ...
    def has_open_for_product(self, product_id: int) -> bool: ...
    def get_pending_for_product(self, product_id: int) -> PurchaseRequest | None: ...


class SupplierOrderRepository(Protocol):
    def get(self, order_id: int) -> SupplierOrder | None: ...
    def list(self) -> list[SupplierOrder]: ...
    def add(self, order: SupplierOrder) -> SupplierOrder: ...
    def save(self, order: SupplierOrder) -> None: ...


class NotificationRepository(Protocol):
    def get(self, notification_id: int) -> Notification | None: ...
    def list_for(self, recipient: Role) -> list[Notification]: ...
    def add(self, notification: Notification) -> Notification: ...
    def save(self, notification: Notification) -> None: ...
